"""
Demo Seeding Script for LearnSphere AI.
Populates realistic demo subjects, documents, chunks, summaries, quizzes, flashcards,
study tasks, and learning analytics for instant exploration.
"""

import asyncio
import uuid
from datetime import date, datetime, timedelta, timezone
from sqlalchemy import select

from app.core.database import AsyncSessionLocal
from app.models.chunk import DocumentChunk
from app.models.conversation import Conversation, ConversationDocument, Message
from app.models.document import Document, DocumentStatus
from app.models.flashcard import Flashcard, FlashcardReview, FlashcardSet
from app.models.learning_activity import LearningActivity
from app.models.quiz import Quiz, QuizAttempt, QuizAttemptAnswer, QuizQuestion
from app.models.study_plan import StudyPlan, StudyPlanDocument, StudyTask
from app.models.subject import Subject
from app.models.summary import Summary, SummarySource
from app.models.user import User, UserPreference


async def seed_data():
    async with AsyncSessionLocal() as session:
        # 1. Ensure Student User
        student_email = "student@learnsphere.ai"
        dev_uuid = uuid.uuid5(uuid.NAMESPACE_DNS, "dev-student.learnsphere.ai")

        user_stmt = select(User).where(User.email == student_email)
        user = (await session.execute(user_stmt)).scalar_one_or_none()
        if not user:
            user = User(
                id=dev_uuid,
                email=student_email,
                full_name="Alex Rivera",
                avatar_url="https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=150",
                is_active=True,
            )
            session.add(user)
            pref = UserPreference(
                user_id=user.id,
                daily_study_goal_minutes=60,
                theme="light",
                notifications_enabled=True,
            )
            session.add(pref)
            await session.flush()

        print(f"User verified: {user.email} ({user.id})")

        # 2. Create Sample Subjects
        bio_sub_stmt = select(Subject).where(Subject.user_id == user.id, Subject.name == "Cellular Biology")
        bio_subject = (await session.execute(bio_sub_stmt)).scalar_one_or_none()
        if not bio_subject:
            bio_subject = Subject(
                user_id=user.id,
                name="Cellular Biology",
                description="Principles of cell structure, energy transduction, and genetics.",
                color="#2563EB",
                icon="BookOpen",
            )
            session.add(bio_subject)
            await session.flush()

        # 3. Create Sample Documents
        doc_stmt = select(Document).where(Document.user_id == user.id, Document.title == "Cell Biology: Respiration & ATP")
        doc = (await session.execute(doc_stmt)).scalar_one_or_none()
        if not doc:
            doc = Document(
                id=uuid.uuid4(),
                user_id=user.id,
                subject_id=bio_subject.id,
                title="Cell Biology: Respiration & ATP",
                original_filename="cellular_respiration_ch3.pdf",
                storage_key="sample/cellular_respiration_ch3.pdf",
                file_size_bytes=2458900,
                page_count=18,
                status=DocumentStatus.READY.value,
                uploaded_at=datetime.now(timezone.utc) - timedelta(days=5),
                processed_at=datetime.now(timezone.utc) - timedelta(days=5),
            )
            session.add(doc)
            await session.flush()

            # Chunks
            c1 = DocumentChunk(
                document_id=doc.id,
                user_id=user.id,
                chunk_index=0,
                content="Mitochondria are membrane-bound organelles that generate most of the chemical energy needed to power the cell's biochemical reactions. Chemical energy produced by the mitochondria is stored in a small molecule called adenosine triphosphate (ATP). Cellular respiration takes place primarily across the inner mitochondrial membrane where ATP synthase harnesses the proton gradient generated by the electron transport chain.",
                page_start=14,
                page_end=15,
                token_count=65,
                embedding=[0.05] * 768,
            )
            c2 = DocumentChunk(
                document_id=doc.id,
                user_id=user.id,
                chunk_index=1,
                content="Glycolysis is an anaerobic metabolic pathway consisting of 10 enzyme-catalyzed reactions that breakdown one glucose molecule into two molecules of pyruvate. It occurs entirely in the cytosol and yields a net gain of 2 ATP and 2 NADH. Phosphofructokinase-1 (PFK-1) acts as the principal rate-limiting and committed enzyme in this pathway.",
                page_start=16,
                page_end=17,
                token_count=62,
                embedding=[0.08] * 768,
            )
            session.add_all([c1, c2])

            # Sample Summary
            summary = Summary(
                user_id=user.id,
                document_id=doc.id,
                title="Cell Respiration: Comprehensive Study Guide",
                summary_type="study_guide",
                content="### 1. Overview\nCellular respiration transfers chemical bond energy from carbohydrates into portable ATP molecules.\n\n### 2. Major Stages\n- **Glycolysis**: Cytosolic breakdown of glucose to pyruvate; net 2 ATP.\n- **Krebs Cycle (Citric Acid Cycle)**: Mitochondrial matrix matrix reactions producing electron carriers.\n- **Oxidative Phosphorylation**: Inner membrane electron transport chain generating maximal ATP via chemiosmosis.",
                key_takeaways=[
                    "Glycolysis yields net 2 ATP and 2 NADH in the cytosol.",
                    "PFK-1 is the key allosteric regulatory enzyme of glycolysis.",
                    "The inner mitochondrial membrane houses the electron transport chain.",
                ],
                model_name="gemini-2.5-flash",
            )
            session.add(summary)

            # Sample Quiz with Attempt
            quiz = Quiz(
                user_id=user.id,
                document_id=doc.id,
                subject_id=bio_subject.id,
                title="Cell Metabolism Mastery Quiz",
                description="Test your understanding of cellular respiration and ATP synthesis.",
                difficulty="medium",
                question_count=2,
                status="published",
                quiz_settings={},
            )
            session.add(quiz)
            await session.flush()

            q1 = QuizQuestion(
                quiz_id=quiz.id,
                question_text="What is the net gain of ATP molecules produced directly by glycolysis?",
                question_type="multiple_choice",
                options=[
                    {"id": "A", "text": "2 ATP"},
                    {"id": "B", "text": "4 ATP"},
                    {"id": "C", "text": "32 ATP"},
                    {"id": "D", "text": "0 ATP"},
                ],
                correct_answer="A",
                explanation="Glycolysis uses 2 ATP during investment and produces 4 ATP, yielding a net 2 ATP.",
                order_index=0,
                topic="Glycolysis",
            )
            q2 = QuizQuestion(
                quiz_id=quiz.id,
                question_text="Where does oxidative phosphorylation take place within the eukaryotic cell?",
                question_type="multiple_choice",
                options=[
                    {"id": "A", "text": "Outer mitochondrial membrane"},
                    {"id": "B", "text": "Inner mitochondrial membrane"},
                    {"id": "C", "text": "Cytosol"},
                    {"id": "D", "text": "Nucleolus"},
                ],
                correct_answer="B",
                explanation="The electron transport chain and ATP synthase complexes reside on the inner mitochondrial membrane.",
                order_index=1,
                topic="Mitochondrial Respiration",
            )
            session.add_all([q1, q2])
            await session.flush()

            # Record Attempt
            attempt = QuizAttempt(
                quiz_id=quiz.id,
                user_id=user.id,
                score=2.0,
                total_points=2.0,
                percentage=100.0,
                status="completed",
                started_at=datetime.now(timezone.utc) - timedelta(days=2),
                submitted_at=datetime.now(timezone.utc) - timedelta(days=2),
            )
            session.add(attempt)
            await session.flush()

            ans1 = QuizAttemptAnswer(
                attempt_id=attempt.id,
                question_id=q1.id,
                user_answer="A",
                is_correct=True,
                points_awarded=1.0,
            )
            ans2 = QuizAttemptAnswer(
                attempt_id=attempt.id,
                question_id=q2.id,
                user_answer="B",
                is_correct=True,
                points_awarded=1.0,
            )
            session.add_all([ans1, ans2])

            # Sample Flashcard Deck
            fc_set = FlashcardSet(
                user_id=user.id,
                document_id=doc.id,
                subject_id=bio_subject.id,
                title="Cell Biology Vocabulary",
                description="Core metabolic terms and definitions.",
                card_count=3,
            )
            session.add(fc_set)
            await session.flush()

            card1 = Flashcard(
                set_id=fc_set.id,
                user_id=user.id,
                front_content="What is ATP Synthase?",
                back_content="A membrane-bound rotary enzyme complex that catalyzes the synthesis of ATP from ADP and inorganic phosphate using a proton gradient.",
                order_index=0,
            )
            card2 = Flashcard(
                set_id=fc_set.id,
                user_id=user.id,
                front_content="What is Chemiosmosis?",
                back_content="The movement of ions across a semipermeable membrane down their electrochemical gradient, used in cellular respiration to generate ATP.",
                order_index=1,
            )
            session.add_all([card1, card2])
            await session.flush()

            # Review log
            rev1 = FlashcardReview(
                flashcard_id=card1.id,
                user_id=user.id,
                rating="good",
                reviewed_at=datetime.now(timezone.utc) - timedelta(days=1),
            )
            session.add(rev1)

            # Sample Study Plan
            today = date.today()
            plan = StudyPlan(
                user_id=user.id,
                subject_id=bio_subject.id,
                title="Biology Midterm Prep (2 Weeks)",
                description="Structured preparation covering Cellular Respiration and Molecular Genetics.",
                start_date=today,
                target_date=today + timedelta(days=14),
                daily_goal_minutes=45,
                status="active",
            )
            session.add(plan)
            await session.flush()

            t1 = StudyTask(
                plan_id=plan.id,
                user_id=user.id,
                document_id=doc.id,
                title="Read Chapter 3: Cellular Respiration",
                description="Review pages 14-18 and take notes on the electron transport chain.",
                scheduled_date=today,
                estimated_minutes=35,
                status="completed",
                completed_at=datetime.now(timezone.utc) - timedelta(hours=3),
                priority="high",
                order_index=0,
            )
            t2 = StudyTask(
                plan_id=plan.id,
                user_id=user.id,
                document_id=doc.id,
                title="Practice Metabolism Quiz",
                description="Take the 2-question knowledge check to verify ATP stoichiometry.",
                scheduled_date=today + timedelta(days=2),
                estimated_minutes=20,
                status="pending",
                priority="medium",
                order_index=1,
            )
            session.add_all([t1, t2])

            # Learning Activities for Analytics
            act1 = LearningActivity(
                user_id=user.id,
                activity_type="document_uploaded",
                document_id=doc.id,
                occurred_at=datetime.now(timezone.utc) - timedelta(days=5),
            )
            act2 = LearningActivity(
                user_id=user.id,
                activity_type="quiz_completed",
                quiz_id=quiz.id,
                attempt_id=attempt.id,
                occurred_at=datetime.now(timezone.utc) - timedelta(days=2),
            )
            act3 = LearningActivity(
                user_id=user.id,
                activity_type="flashcard_reviewed",
                flashcard_set_id=fc_set.id,
                occurred_at=datetime.now(timezone.utc) - timedelta(days=1),
            )
            act4 = LearningActivity(
                user_id=user.id,
                activity_type="study_task_completed",
                study_task_id=t1.id,
                occurred_at=datetime.now(timezone.utc) - timedelta(hours=3),
            )
            session.add_all([act1, act2, act3, act4])

        await session.commit()
        print("Demo data seeded successfully! You can now log in with student demo credentials.")


if __name__ == "__main__":
    asyncio.run(seed_data())
